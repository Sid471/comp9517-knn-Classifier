# Model selection
# ---------------------------------------------------------------------------
def tune_knn(X_train, y_train, X_val, y_val):
    """Grid-search neighbourhood size, distance metric and weighting.

    Selection is performed exclusively on the validation split so that the test
    split remains unseen until final evaluation.
    """
    results = []
    best = {"accuracy": -1.0}

    for metric in CONFIG.METRIC_GRID:
        for weights in CONFIG.WEIGHTS_GRID:
            for k in CONFIG.K_GRID:
                model = KNeighborsClassifier(n_neighbors=k, weights=weights,
                                             metric=metric, n_jobs=CONFIG.N_JOBS)
                model.fit(X_train, y_train)
                accuracy = accuracy_score(y_val, model.predict(X_val))
                results.append((metric, weights, k, accuracy))
                if accuracy > best["accuracy"]:
                    best = {"accuracy": accuracy, "k": k,
                            "weights": weights, "metric": metric}
                print(f"metric={metric:<9} weights={weights:<8} k={k:<2} "
                      f"validation accuracy={accuracy:.4f}")

    print(f"Selected configuration: {best}")
    _plot_hyperparameter_sweep(results)
    return best


def _plot_hyperparameter_sweep(results):
    """Plot validation accuracy against k for each metric/weighting pair."""
    plt.figure(figsize=(7, 5))
    for metric in CONFIG.METRIC_GRID:
        for weights in CONFIG.WEIGHTS_GRID:
            points = sorted((k, acc) for m, w, k, acc in results
                            if m == metric and w == weights)
            plt.plot([p[0] for p in points], [p[1] for p in points],
                     marker="o", label=f"{metric}/{weights}")
    plt.xlabel("Number of neighbours (k)")
    plt.ylabel("Validation accuracy")
    plt.title("KNN hyperparameter sweep")
    plt.legend(fontsize=8)
    plt.grid(alpha=0.3)
    plt.savefig(os.path.join(CONFIG.OUT_DIR, "knn_k_sweep.png"),
                dpi=150, bbox_inches="tight")
    plt.close()

