# Evaluation
# ---------------------------------------------------------------------------
def evaluate(best, X_train, y_train, X_test, y_test):
    """Fit the selected model and report performance on the held-out test set."""
    model = KNeighborsClassifier(n_neighbors=best["k"], weights=best["weights"],
                                 metric=best["metric"], n_jobs=CONFIG.N_JOBS)

    started = time.time()
    model.fit(X_train, y_train)
    train_seconds = time.time() - started

    started = time.time()
    predictions = model.predict(X_test)
    test_seconds = time.time() - started
    probabilities = model.predict_proba(X_test)

    classes = model.classes_
    top1 = accuracy_score(y_test, predictions)
    top5 = top_k_accuracy_score(y_test, probabilities, k=5, labels=classes)
    balanced = balanced_accuracy_score(y_test, predictions)
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_test, predictions, average="macro", zero_division=0)

    print("\nKNN test results")
    print(f"  configuration      k={best['k']}, weights={best['weights']}, "
          f"metric={best['metric']}, PCA={CONFIG.PCA_DIMS}")
    print(f"  top-1 accuracy     {top1:.4f}")
    print(f"  top-5 accuracy     {top5:.4f}")
    print(f"  balanced accuracy  {balanced:.4f}")
    print(f"  macro precision    {precision:.4f}")
    print(f"  macro recall       {recall:.4f}")
    print(f"  macro F1           {f1:.4f}")
    print(f"  training time      {train_seconds:.2f}s")
    print(f"  inference time     {test_seconds:.2f}s "
          f"({test_seconds / len(y_test) * 1000:.2f} ms/image)")

    matrix = confusion_matrix(y_test, predictions, labels=classes)
    plt.figure(figsize=(9, 8))
    plt.imshow(np.log1p(matrix), cmap="viridis")
    plt.title("KNN confusion matrix (log-scaled)")
    plt.xlabel("Predicted class")
    plt.ylabel("True class")
    plt.colorbar()
    plt.savefig(os.path.join(CONFIG.OUT_DIR, "knn_confusion_matrix.png"),
                dpi=150, bbox_inches="tight")
    plt.close()

    # Most frequently confused class pairs, for error analysis.
    off_diagonal = matrix.copy()
    np.fill_diagonal(off_diagonal, 0)
    pairs = sorted(
        ((off_diagonal[i, j], classes[i], classes[j])
         for i in range(len(classes)) for j in range(len(classes))
         if off_diagonal[i, j] > 0),
        reverse=True)
    print("\nMost frequently confused class pairs (true -> predicted, count)")
    for count, true_class, predicted_class in pairs[:15]:
        print(f"  {true_class} -> {predicted_class}: {count}")

    metrics = {
        "top1": top1, "top5": top5, "balanced_accuracy": balanced,
        "macro_precision": precision, "macro_recall": recall, "macro_f1": f1,
        "train_seconds": train_seconds, "test_seconds": test_seconds,
        "configuration": best, "pca_dimensions": CONFIG.PCA_DIMS,
    }
    with open(os.path.join(CONFIG.OUT_DIR, "knn_metrics.json"), "w") as handle:
        json.dump(metrics, handle, indent=2, default=str)
    with open(os.path.join(CONFIG.OUT_DIR, "knn_classification_report.txt"), "w") as handle:
        handle.write(classification_report(y_test, predictions, zero_division=0))

    return metrics

# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main():
    mount_drive()

    os.makedirs(CONFIG.WORK_DIR, exist_ok=True)
    os.makedirs(CONFIG.CACHE_DIR, exist_ok=True)
    os.makedirs(CONFIG.OUT_DIR, exist_ok=True)
    np.random.seed(CONFIG.RANDOM_SEED)

    train_split = load_split(CONFIG.TRAIN_CSV)
    val_split = load_split(CONFIG.VAL_CSV)
    test_split = load_split(CONFIG.TEST_CSV)

    extract_needed_images([train_split, val_split, test_split])

    X_train_raw, y_train = build_feature_matrix(train_split, "train")
    X_val_raw, y_val = build_feature_matrix(val_split, "val")
    X_test_raw, y_test = build_feature_matrix(test_split, "test")

    # Standardisation and PCA are fitted on the training split alone; the
    # validation and test splits are only transformed, preventing leakage.
    scaler = StandardScaler().fit(X_train_raw)
    pca = PCA(n_components=min(CONFIG.PCA_DIMS, X_train_raw.shape[1]),
              random_state=CONFIG.RANDOM_SEED).fit(scaler.transform(X_train_raw))

    def project(matrix):
        return pca.transform(scaler.transform(matrix))

    X_train, X_val, X_test = project(X_train_raw), project(X_val_raw), project(X_test_raw)
    print(f"PCA retained {pca.n_components_} components "
          f"({pca.explained_variance_ratio_.sum():.3f} of total variance)")

    best = tune_knn(X_train, y_train, X_val, y_val)
    evaluate(best, X_train, y_train, X_test, y_test)


if __name__ == "__main__":
    main()

