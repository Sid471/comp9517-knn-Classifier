class CONFIG:
    """Central configuration for paths, feature extraction and the classifier."""

    # Directory at which Google Drive is mounted.
    MOUNT_POINT = "/content/gdrive"
    # Dataset location: label CSVs and the two source archives.
    DRIVE_ROOT = "/content/gdrive/MyDrive/CV_Proj_Dataset"
    # Destination for cached features, metrics and figures.
    RESULTS_ROOT = "/content/gdrive/MyDrive/COMP9517 GROUP PROJECT"
    # Local working directory holding the extracted JPEGs.
    WORK_DIR = "/content/work"

    # train/val images reside in train_mini.tar.gz; test images in val.tar.gz.
    TRAIN_TAR = "train_mini.tar.gz"
    VAL_TAR = "val.tar.gz"

    TRAIN_CSV = "train_label_500_species.csv"
    VAL_CSV = "val_label_500_species.csv"
    TEST_CSV = "test_label_500_species.csv"
    IMG_PATH_COL = "file_name"
    LABEL_COL = "category_id"

    # Feature extraction.
    IMG_SIZE = 128              # images are resized to IMG_SIZE x IMG_SIZE
    HSV_BINS = (8, 8, 8)        # colour histogram bins per HSV channel
    COLOR_GRID = 2              # image split into COLOR_GRID x COLOR_GRID cells
    HOG_PPC = (16, 16)          # HOG pixels per cell
    HOG_CPB = (2, 2)            # HOG cells per block
    HOG_ORIENT = 9              # HOG gradient orientation bins
    LBP_P = 24                  # LBP neighbourhood size
    LBP_R = 3                   # LBP radius
    LBP_BINS = LBP_P + 2        # bins in the uniform LBP histogram

    # Relative contribution of each descriptor block to the distance metric.
    W_COLOR = 1.0
    W_HOG = 1.0
    W_LBP = 1.0
    FEATURE_VER = "v2"          # identifier used to key the feature cache

    # Dimensionality reduction and classifier search space.
    PCA_DIMS = 300
    K_GRID = [1, 3, 5, 7, 9, 15, 21, 31, 41, 51]
    WEIGHTS_GRID = ["uniform", "distance"]
    METRIC_GRID = ["euclidean", "cosine"]

    N_JOBS = -1
    RANDOM_SEED = 42

    CACHE_DIR = os.path.join(RESULTS_ROOT, "knn_cache")
    OUT_DIR = os.path.join(RESULTS_ROOT, "knn_outputs")

