def _l2_normalise(vector):
    """Scale a vector to unit L2 norm."""
    vector = np.asarray(vector, dtype="float32")
    return vector / (np.linalg.norm(vector) + 1e-7)


def extract_features(image_path):
    """Compute the combined colour, gradient and texture descriptor.

    The three descriptor blocks are normalised independently before being
    concatenated so that a high-dimensional block (HOG) cannot dominate the
    distance computation simply by virtue of its length.
    """
    image = cv2.imread(image_path)
    if image is None:
        return None

    image = cv2.resize(image, (CONFIG.IMG_SIZE, CONFIG.IMG_SIZE))
    hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)
    grey = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Spatial colour: one HSV histogram per grid cell preserves coarse layout.
    cell_size = CONFIG.IMG_SIZE // CONFIG.COLOR_GRID
    cell_histograms = []
    for row in range(CONFIG.COLOR_GRID):
        for col in range(CONFIG.COLOR_GRID):
            cell = hsv[row * cell_size:(row + 1) * cell_size,
                       col * cell_size:(col + 1) * cell_size]
            histogram = cv2.calcHist([cell], [0, 1, 2], None, CONFIG.HSV_BINS,
                                     [0, 180, 0, 256, 0, 256]).flatten()
            cell_histograms.append(_l2_normalise(histogram))
    colour = _l2_normalise(np.concatenate(cell_histograms))

    # Gradient structure.
    gradients = _l2_normalise(hog(
        grey, orientations=CONFIG.HOG_ORIENT, pixels_per_cell=CONFIG.HOG_PPC,
        cells_per_block=CONFIG.HOG_CPB, block_norm="L2-Hys", feature_vector=True))

    # Micro-texture.
    lbp = local_binary_pattern(grey, CONFIG.LBP_P, CONFIG.LBP_R, method="uniform")
    texture, _ = np.histogram(lbp.ravel(),
                              bins=np.arange(0, CONFIG.LBP_BINS + 1),
                              range=(0, CONFIG.LBP_BINS))
    texture = _l2_normalise(texture)

    return np.concatenate([
        CONFIG.W_COLOR * colour,
        CONFIG.W_HOG * gradients,
        CONFIG.W_LBP * texture,
    ]).astype("float32")


def build_feature_matrix(split, split_name):
    """Build, cache and return the feature matrix and labels for one split."""
    cache_x = os.path.join(CONFIG.CACHE_DIR, f"X_{split_name}_{CONFIG.FEATURE_VER}.npy")
    cache_y = os.path.join(CONFIG.CACHE_DIR, f"y_{split_name}_{CONFIG.FEATURE_VER}.npy")
    if os.path.exists(cache_x) and os.path.exists(cache_y):
        print(f"{split_name}: loaded cached features")
        return np.load(cache_x), np.load(cache_y)

    paths = [os.path.join(CONFIG.WORK_DIR, name) for name in split["img"]]
    labels = split["label"].to_numpy()

    print(f"{split_name}: extracting features for {len(paths)} images")
    started = time.time()
    features = Parallel(n_jobs=CONFIG.N_JOBS)(
        delayed(extract_features)(path) for path in paths)

    usable = [i for i, feature in enumerate(features) if feature is not None]
    if not usable:
        raise RuntimeError(
            f"No readable images for the '{split_name}' split; the source "
            f"archive for this split is missing or empty.")

    X = np.vstack([features[i] for i in usable])
    y = labels[usable]
    print(f"{split_name}: {X.shape[0]} samples, {X.shape[1]} dimensions "
          f"({time.time() - started:.0f}s)")

    np.save(cache_x, X)
    np.save(cache_y, y)
    return X, y

