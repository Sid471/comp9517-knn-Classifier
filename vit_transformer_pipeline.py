class SpeciesDataset(Dataset):
    """Image dataset backed by a label CSV and a directory of JPEGs."""

    def __init__(self, split, label_to_index, transform):
        paths = [os.path.join(CONFIG.WORK_DIR, name) for name in split["img"]]
        labels = [label_to_index[label] for label in split["label"]]

        available = [i for i, path in enumerate(paths) if os.path.exists(path)]
        self.paths = [paths[i] for i in available]
        self.labels = [labels[i] for i in available]
        self.transform = transform

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, index):
        image = Image.open(self.paths[index]).convert("RGB")
        return self.transform(image), self.labels[index]


def build_loaders(train_split, val_split, test_split, label_to_index):
    """Construct the training, validation and test data loaders.

    Normalisation statistics are taken from the backbone's own configuration.
    RandAugment is applied to the training split only; validation and test use
    deterministic resize-and-centre-crop transforms.
    """
    data_config = resolve_data_config(
        {}, model=timm.create_model(CONFIG.BACKBONE, pretrained=False))

    train_transform = create_transform(
        input_size=CONFIG.IMG_SIZE, is_training=True,
        mean=data_config["mean"], std=data_config["std"],
        auto_augment="rand-m7-mstd0.5")
    eval_transform = create_transform(
        input_size=CONFIG.IMG_SIZE, is_training=False,
        mean=data_config["mean"], std=data_config["std"])

    def loader(dataset, shuffle):
        return DataLoader(dataset, batch_size=CONFIG.BATCH_SIZE, shuffle=shuffle,
                          num_workers=CONFIG.NUM_WORKERS, pin_memory=True,
                          drop_last=shuffle)

    return (
        loader(SpeciesDataset(train_split, label_to_index, train_transform), True),
        loader(SpeciesDataset(val_split, label_to_index, eval_transform), False),
        loader(SpeciesDataset(test_split, label_to_index, eval_transform), False),
    )

