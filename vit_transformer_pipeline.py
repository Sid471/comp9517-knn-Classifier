# Evaluation
# ---------------------------------------------------------------------------
def evaluate(mode, model, test_loader, num_classes, train_seconds, history):
    """Report test performance and write metrics and figures to disk."""
    started = time.time()
    top1, y_true, y_pred, probabilities = predict(model, test_loader,
                                                  return_probabilities=True)
    test_seconds = time.time() - started

    labels = np.arange(num_classes)
    top5 = top_k_accuracy_score(y_true, probabilities, k=5, labels=labels)
    balanced = balanced_accuracy_score(y_true, y_pred)
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="macro", zero_division=0)

    print(f"\nViT-B/16 [{mode}] test results")
    print(f"  top-1 accuracy     {top1:.4f}")
    print(f"  top-5 accuracy     {top5:.4f}")
    print(f"  balanced accuracy  {balanced:.4f}")
    print(f"  macro precision    {precision:.4f}")
    print(f"  macro recall       {recall:.4f}")
    print(f"  macro F1           {f1:.4f}")
    print(f"  training time      {train_seconds:.0f}s")
    print(f"  inference time     {test_seconds:.1f}s "
          f"({test_seconds / len(y_true) * 1000:.2f} ms/image)")

    tag = f"vit_{mode}"

    matrix = confusion_matrix(y_true, y_pred, labels=labels)
    plt.figure(figsize=(9, 8))
    plt.imshow(np.log1p(matrix), cmap="viridis")
    plt.title(f"ViT-B/16 [{mode}] confusion matrix (log-scaled)")
    plt.xlabel("Predicted class")
    plt.ylabel("True class")
    plt.colorbar()
    plt.savefig(os.path.join(CONFIG.OUT_DIR, f"{tag}_confusion.png"),
                dpi=150, bbox_inches="tight")
    plt.close()

    epochs = range(1, len(history["train_loss"]) + 1)
    figure, loss_axis = plt.subplots(figsize=(7, 5))
    loss_axis.plot(epochs, history["train_loss"], "b-o")
    loss_axis.set_xlabel("Epoch")
    loss_axis.set_ylabel("Training loss", color="b")
    accuracy_axis = loss_axis.twinx()
    accuracy_axis.plot(epochs, history["val_accuracy"], "r-s")
    accuracy_axis.set_ylabel("Validation top-1 accuracy", color="r")
    plt.title(f"ViT-B/16 [{mode}] training dynamics")
    plt.savefig(os.path.join(CONFIG.OUT_DIR, f"{tag}_curves.png"),
                dpi=150, bbox_inches="tight")
    plt.close()

    metrics = {
        "mode": mode, "top1": top1, "top5": top5, "balanced_accuracy": balanced,
        "macro_precision": precision, "macro_recall": recall, "macro_f1": f1,
        "train_seconds": train_seconds, "test_seconds": test_seconds,
        "epochs": len(history["train_loss"]), "backbone": CONFIG.BACKBONE,
    }
    with open(os.path.join(CONFIG.OUT_DIR, f"{tag}_metrics.json"), "w") as handle:
        json.dump(metrics, handle, indent=2, default=str)
    with open(os.path.join(CONFIG.OUT_DIR, f"{tag}_report.txt"), "w") as handle:
        handle.write(classification_report(y_true, y_pred, zero_division=0))
    torch.save(model.state_dict(), os.path.join(CONFIG.OUT_DIR, f"{tag}_weights.pt"))

    return metrics

# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main():
    print(f"Device: {DEVICE}")
    mount_drive()

    train_split = load_split(CONFIG.TRAIN_CSV)
    val_split = load_split(CONFIG.VAL_CSV)
    test_split = load_split(CONFIG.TEST_CSV)

    extract_needed_images([train_split, val_split, test_split])

    # Map the dataset's category identifiers onto a contiguous index range, as
    # required by the cross-entropy objective.
    classes = sorted(train_split["label"].unique())
    label_to_index = {label: index for index, label in enumerate(classes)}
    num_classes = len(classes)
    with open(os.path.join(CONFIG.OUT_DIR, "vit_label_map.json"), "w") as handle:
        json.dump({str(k): v for k, v in label_to_index.items()}, handle)
    print(f"{num_classes} classes")

    train_loader, val_loader, test_loader = build_loaders(
        train_split, val_split, test_split, label_to_index)

    results = {}
    for mode in ("pretrained", "scratch"):
        model, history, train_seconds = train_model(
            mode, train_loader, val_loader, num_classes)
        results[mode] = evaluate(mode, model, test_loader, num_classes,
                                 train_seconds, history)

    print("\nSummary")
    for mode, metrics in results.items():
        print(f"  {mode:<11} top-1 {metrics['top1']:.4f}  "
              f"top-5 {metrics['top5']:.4f}  macro F1 {metrics['macro_f1']:.4f}")


if __name__ == "__main__":
    main()