def _extract_from_archive(tar_path, wanted):
    """Stream a tar archive once, extracting only the requested filenames."""
    if not wanted:
        return
    if not os.path.exists(tar_path):
        print(f"Archive unavailable: {tar_path} ({len(wanted)} images skipped)")
        return

    extracted = 0
    started = time.time()
    with tarfile.open(tar_path, "r:gz") as archive:
        for member in archive:
            if not member.isfile():
                continue
            name = os.path.basename(member.name)
            if name in wanted:
                source = archive.extractfile(member)
                if source is None:
                    continue
                with open(os.path.join(CONFIG.WORK_DIR, name), "wb") as target:
                    target.write(source.read())
                extracted += 1
                wanted.discard(name)
                if not wanted:
                    break
    print(f"{os.path.basename(tar_path)}: extracted {extracted} images "
          f"in {time.time() - started:.0f}s")


def extract_needed_images(splits):
    """Extract only the images referenced by the 500-class subset."""
    present = set(os.listdir(CONFIG.WORK_DIR))
    wanted = {CONFIG.TRAIN_TAR: set(), CONFIG.VAL_TAR: set()}

    for split in splits:
        for full_path, name in zip(split["img_full"], split["img"]):
            if name in present:
                continue
            prefix = str(full_path).split("/", 1)[0]
            archive = CONFIG.VAL_TAR if prefix == "val" else CONFIG.TRAIN_TAR
            wanted[archive].add(name)

    if not any(wanted.values()):
        print("All required images are already available.")
        return

    for archive, names in wanted.items():
        _extract_from_archive(os.path.join(CONFIG.DRIVE_ROOT, archive), names)

