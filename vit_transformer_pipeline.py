# Training and inference
# ---------------------------------------------------------------------------
@torch.no_grad()
def predict(model, loader, return_probabilities=False):
    """Run inference over a loader and return labels, predictions and scores."""
    model.eval()
    all_labels, all_predictions, all_probabilities = [], [], []

    for images, labels in loader:
        images = images.to(DEVICE, non_blocking=True)
        with autocast_context():
            logits = model(images)
        probabilities = torch.softmax(logits.float(), dim=1).cpu().numpy()
        all_predictions.append(probabilities.argmax(1))
        all_labels.append(labels.numpy())
        if return_probabilities:
            all_probabilities.append(probabilities)

    y_true = np.concatenate(all_labels)
    y_pred = np.concatenate(all_predictions)
    probabilities = np.concatenate(all_probabilities) if return_probabilities else None
    return accuracy_score(y_true, y_pred), y_true, y_pred, probabilities


def train_model(mode, train_loader, val_loader, num_classes):
    """Train ViT-B/16 in either the 'pretrained' or 'scratch' setting.

    The parameters achieving the highest validation accuracy are retained, so
    that the reported test performance corresponds to the selected checkpoint
    rather than the final epoch.
    """
    pretrained = mode == "pretrained"
    epochs = CONFIG.EPOCHS_PRETRAINED if pretrained else CONFIG.EPOCHS_SCRATCH
    learning_rate = CONFIG.LR_PRETRAINED if pretrained else CONFIG.LR_SCRATCH

    print(f"\nTraining ViT-B/16 [{mode}]: {epochs} epochs, "
          f"learning rate {learning_rate}, device {DEVICE}")

    model = timm.create_model(CONFIG.BACKBONE, pretrained=pretrained,
                              num_classes=num_classes).to(DEVICE)
    optimiser = torch.optim.AdamW(model.parameters(), lr=learning_rate,
                                  weight_decay=CONFIG.WEIGHT_DECAY)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimiser, T_max=epochs)
    criterion = nn.CrossEntropyLoss(label_smoothing=CONFIG.LABEL_SMOOTHING)
    scaler = torch.cuda.amp.GradScaler(enabled=USE_AMP)

    history = {"train_loss": [], "val_accuracy": []}
    best_accuracy, best_state = -1.0, None
    started = time.time()

    for epoch in range(1, epochs + 1):
        model.train()
        running_loss, seen = 0.0, 0

        for images, labels in train_loader:
            images = images.to(DEVICE, non_blocking=True)
            labels = labels.to(DEVICE, non_blocking=True)
            optimiser.zero_grad(set_to_none=True)

            if USE_AMP:
                with autocast_context():
                    loss = criterion(model(images), labels)
                scaler.scale(loss).backward()
                scaler.step(optimiser)
                scaler.update()
            else:
                loss = criterion(model(images), labels)
                loss.backward()
                optimiser.step()

            running_loss += loss.item() * images.size(0)
            seen += images.size(0)

        scheduler.step()
        train_loss = running_loss / max(seen, 1)
        val_accuracy = predict(model, val_loader)[0]
        history["train_loss"].append(train_loss)
        history["val_accuracy"].append(val_accuracy)
        print(f"  epoch {epoch:>2}  train loss {train_loss:.3f}  "
              f"validation top-1 {val_accuracy:.4f}")

        if val_accuracy > best_accuracy:
            best_accuracy = val_accuracy
            best_state = {k: v.detach().cpu().clone()
                          for k, v in model.state_dict().items()}

    train_seconds = time.time() - started
    if best_state is not None:
        model.load_state_dict(best_state)
    print(f"  best validation top-1 {best_accuracy:.4f} "
          f"({train_seconds:.0f}s total)")

    return model, history, train_seconds

