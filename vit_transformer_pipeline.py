def _basename(path):
    """Reduce a dataset-relative path to its filename."""
    return os.path.basename(str(path).strip())


def load_split(csv_name):
    """Read a label CSV and return its image filenames and class labels."""
    df = pd.read_csv(os.path.join(CONFIG.DRIVE_ROOT, csv_name))
    columns = {c.lower(): c for c in df.columns}

    img_col = CONFIG.IMG_PATH_COL if CONFIG.IMG_PATH_COL in df.columns else next(
        (columns[c] for c in ("file_name", "filename", "image", "path", "img")
         if c in columns), None)
    label_col = CONFIG.LABEL_COL if CONFIG.LABEL_COL in df.columns else next(
        (columns[c] for c in ("category_id", "label", "class_id", "species")
         if c in columns), None)
    if img_col is None or label_col is None:
        raise ValueError(f"Could not identify image/label columns in {csv_name}.")

    split = pd.DataFrame({
        "img_full": df[img_col].astype(str),
        "img": df[img_col].map(_basename),
        "label": df[label_col],
    })
    print(f"{csv_name}: {len(split)} images, {split['label'].nunique()} classes")
    return split

